async def main():
    out_dir = os.path.join(os.path.dirname(__file__), "..", "materials", "audio", "summer-night-vocab-quiz")
    out_dir = os.path.abspath(out_dir)
    os.makedirs(out_dir, exist_ok=True)
    print(f"Output directory: {out_dir}")

    sem = asyncio.Semaphore(5)

    async def synth(text, filepath):
        if os.path.exists(filepath) and os.path.getsize(filepath) > 0:
            return
        async with sem:
            tts = edge_tts.Communicate(text, voice="zh-TW-HsiaoChenNeural", rate="-4%")
            await tts.save(filepath)
            print(f"Generated: {os.path.basename(filepath)}")

    tasks = []
    for q in questions_data:
        qid_str = f"q{q['id']:02d}"
        # Question audio
        tasks.append(synth(q["tts_q"], os.path.join(out_dir, f"{qid_str}-question.mp3")))
        # Option audios
        for opt_key, opt_text, tts_opt in q["options"]:
            tasks.append(synth(tts_opt, os.path.join(out_dir, f"{qid_str}-{opt_key}.mp3")))

    print(f"Starting synthesis of {len(tasks)} audio clips...")
    await asyncio.gather(*tasks)
    print("All audio clips synthesized successfully!")

if __name__ == "__main__":
    asyncio.run(main())
